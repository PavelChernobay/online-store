package org.onlinestore.orderservice.entity;

/**
 * Перечисление ролей пользователя в системе.
 * Используется для разграничения доступа к различным эндпоинтам и операциям.
 */
public enum Role {

    /** Обычный пользователь системы */
    ROLE_USER,

    /** Администратор с расширенными правами */
    ROLE_ADMIN

}